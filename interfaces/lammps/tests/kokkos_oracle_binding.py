#!/usr/bin/env python3
"""Explicit, hash-locked portable reference rebinding; no oracle is executed."""
import argparse
import json
from pathlib import Path
from kokkos_benchmark import require, sha

ORIGINAL = '3b5cf118054cbf29b48d89fc0c526077704646f25b5a2f4bc21bdedddc04de75'
PORTABLE = '8d7fcb48a2935f42e68a6fa9ca27896d4b6f53bbf7d5933c25f1282b34969776'
AUDIT = '42dda07c890e7a5b58a733b169a8c01e99bd3ee8713229d3b5261bb66c4fc6af'
BRIDGE = '364fb8dd10f565e850f9a7fff545ff5e0bb93b6953a341679df447e31ed338a3'
BUILD = 'b657d4fe1d206409fb7febf516ff19f4cf30a6190cfecd3f79b9f7cbbeb6f1a5'
MATRIX57 = 'ef6aed466aec53bd40d44fc1d6dd6121b920f1d2644ba9c54345d6feb50eae63'
MATRIX320 = '6402c92a54a39899e0205615c4799564b3b47f0584f2cc31e60ad81fe9712425'
AUDITOR = '355977fbbc7e786879d7a3a41799b0c01461e23a2534fdd2f975a065b608f768'
SOURCE = '14c1907b565175aa021852bc6bd578a254b6b5bc6cb0d47a1e7bc4390dfdc402'
COMMIT = '392cb02f6c2129c0b2e3b698b6ce082720fe8bef'


def validate_reference(native, audit_path=None, extension_matrix=None):
    native = Path(native).resolve()
    digest = sha(native)
    if digest == ORIGINAL:
        require(audit_path is None, 'An original oracle must not masquerade as the validated portable reference')
        return dict(mode='ORIGINAL_FROZEN', native=str(native), native_sha256=ORIGINAL, cuda_qualified=False)
    require(digest == PORTABLE, 'Unrecognized native binary; reference hash guard remains enforced')
    require(audit_path is not None and extension_matrix is not None, 'Portable reference requires the exact raw-audit and frozen57 receipts')
    audit_path, matrix_path = Path(audit_path).resolve(), Path(extension_matrix).resolve()
    require(sha(audit_path) == AUDIT, 'Portable independent raw-evidence audit changed')
    root = audit_path.parent
    bridge_path = root / 'portable-oracle-bridge-r1/bridge.json'
    build_path = root / 'native-oracle-portable-r1/build-receipt.json'
    auditor_path = root / 'native-oracle-bridge-audit-355977fbbc7e.py'
    require(sha(bridge_path) == BRIDGE and sha(build_path) == BUILD and sha(auditor_path) == AUDITOR,
            'Portable bridge/build/auditor provenance changed')
    require(sha(matrix_path) == MATRIX57, 'Only the original-oracle frozen57 matrix is allowed; do not regenerate it')
    audit = json.loads(audit_path.read_text())
    bridge = json.loads(bridge_path.read_text())
    build = json.loads(build_path.read_text())
    require(audit['status'] == 'PASS_ORACLE_BINDING_VERIFIED' and audit['validated_native_sha256'] == PORTABLE and
            audit['original_native_sha256'] == ORIGINAL and not audit['cuda_qualified'], 'Independent reference audit not validated')
    require((audit['source_files_checked'], audit['efs_checks'], audit['roundtrip_checks'], audit['init_checks'],
             audit['nonzero_zbl_probes']) == (175, 400, 380, 57, 4), 'Independent bridge coverage incomplete')
    require(bridge['status'] == 'PASS' and bridge['validated_native_sha256'] == PORTABLE and
            bridge['extension_matrix_sha256'] == MATRIX57 and bridge['matrix_sha256'] == MATRIX320,
            'Bridge model scope/reference differs')
    require(build['binary_sha256'] == PORTABLE and build['source_unchanged'] and
            build['dependency_audit'] == 'PASS_NO_INTEL_MKL_MPI', 'Portable build is not the audited unchanged source')
    require(build['source_commit'] == COMMIT and build['source_archive_sha256'] == SOURCE and
            sha(Path(build['source_archive'])) == SOURCE, 'Frozen native mathematical source changed')
    require(bridge['tolerance']['absolute'] == 1e-9 and bridge['tolerance']['relative'] == 1e-9,
            'Native bridge tolerance changed')
    matrix = json.loads(matrix_path.read_text())
    require(len(matrix['cases']) == 57 and matrix['native_sha256'] == ORIGINAL,
            'Supplement must have been generated by the original frozen oracle')
    for case in matrix['cases']:
        require(sha(matrix_path.parent / Path(case['model']).name) == case['sha256'], 'Frozen57 model changed')
    return dict(mode='VALIDATED_PORTABLE', native=str(native), native_sha256=PORTABLE,
                original_native_sha256=ORIGINAL, audit_path=str(audit_path), audit_sha256=AUDIT,
                bridge_sha256=BRIDGE, build_receipt_sha256=BUILD, auditor_sha256=AUDITOR,
                extension_matrix=str(matrix_path), extension_matrix_sha256=MATRIX57,
                core_matrix_sha256=MATRIX320, source_commit=COMMIT, source_archive_sha256=SOURCE,
                cpu_bridge='175 source /400 EFS /380 roundtrip /57 init /4 nonzero ZBL independently rechecked',
                cuda_qualified=False, amd_native_execution='Required in this new compute allocation; no CPU bridge implies GPU PASS')


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--native', type=Path, required=True)
    p.add_argument('--audit', type=Path)
    p.add_argument('--extension-matrix', type=Path)
    a = p.parse_args()
    print(json.dumps(validate_reference(a.native, a.audit, a.extension_matrix)))
